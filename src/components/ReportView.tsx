import { useState } from 'react';
import {
  Volume2, VolumeX, Pause, Printer, Home, CheckCircle2, FileText,
  MapPin, Phone, ArrowRight, ListChecks, ExternalLink, RefreshCw, Building2, HandHeart,
  MessageCircle,
} from 'lucide-react';
import { useTextToSpeech } from '@/hooks/useVoice';
import type { MatchResult, IntakeAnswers } from '@/types';
import { intakeQuestions } from '@/lib/intakeQuestions';

interface ReportViewProps {
  result: MatchResult;
  answers: IntakeAnswers;
  onRestart: () => void;
  onHome: () => void;
  language: 'en' | 'hi' | 'kn';
}

export default function ReportView({ result, answers, onRestart, onHome, language }: ReportViewProps) {
  const [isReading, setIsReading] = useState(false);
  const [currentSection, setCurrentSection] = useState(0);
  const { speak, stop, isSupported: ttsSupported } = useTextToSpeech(language);

  const eligibleCount = result.eligibleSchemes.length;
  const ngoCount = result.eligibleNGOs.length;

  const buildFullSpeechText = (): string => {
    const parts: string[] = [];

    if (eligibleCount === 0) {
      parts.push('Based on your answers, no government schemes were matched. However, there are NGOs that may still be able to help you.');
    } else {
      parts.push(`You are eligible for ${eligibleCount} financial support scheme${eligibleCount > 1 ? 's' : ''}.`);
      result.eligibleSchemes.forEach((match, i) => {
        parts.push(`Scheme ${i + 1}: ${match.scheme.scheme_name}. ${match.reasons.join(' ')}. Coverage: ${match.scheme.coverage_amount || 'Not specified'}.`);
      });
    }

    if (ngoCount > 0) {
      parts.push(`There ${ngoCount > 1 ? 'are' : 'is'} also ${ngoCount} NGO${ngoCount > 1 ? 's' : ''} that can help you:`);
      result.eligibleNGOs.forEach((ngo, i) => {
        parts.push(`${i + 1}. ${ngo.org_name}. ${ngo.focus_area || ''}.`);
      });
    }

    if (result.nearbyHelpDesks.length > 0) {
      parts.push('Here are the nearest help desks you can visit:');
      result.nearbyHelpDesks.forEach((desk, i) => {
        parts.push(`${i + 1}. ${desk.name}. ${desk.address || ''}. Phone: ${desk.phone || 'Not available'}.`);
      });
    }

    if (result.nextSteps.length > 0) {
      parts.push('Your next steps:');
      result.nextSteps.forEach((step, i) => {
        parts.push(`${i + 1}. ${step}`);
      });
    }

    parts.push('You can print this report and carry it to the hospital help desk.');
    return parts.join(' ');
  };

  const buildWhatsAppMessage = (): string => {
    const lines: string[] = [];

    lines.push('🏥 *Sahaay - Financial Eligibility Report*');
    lines.push('');
    lines.push('📋 *Summary*');
    lines.push(`You are eligible for *${eligibleCount}* scheme(s) and *${ngoCount}* NGO(s).`);
    lines.push('');

    if (eligibleCount > 0) {
      lines.push('💰 *Government Schemes You Qualify For:*');
      result.eligibleSchemes.forEach((match, idx) => {
        lines.push(`${idx + 1}. *${match.scheme.scheme_name}*`);
        if (match.scheme.coverage_amount) {
          lines.push(`   Coverage: ${match.scheme.coverage_amount}`);
        }
        lines.push(`   Administering Body: ${match.scheme.administering_body}`);
        match.reasons.forEach((reason) => {
          lines.push(`   • ${reason}`);
        });
        lines.push('');
      });
    }

    if (ngoCount > 0) {
      lines.push('🤝 *NGOs That Can Help:*');
      result.eligibleNGOs.forEach((ngo, idx) => {
        lines.push(`${idx + 1}. *${ngo.org_name}*`);
        if (ngo.focus_area) {
          lines.push(`   Focus: ${ngo.focus_area}`);
        }
        if (ngo.contact_info) {
          lines.push(`   Contact: ${ngo.contact_info}`);
        }
        lines.push('');
      });
    }

    if (result.nearbyHelpDesks.length > 0) {
      lines.push('📍 *Nearest Help Desks:*');
      result.nearbyHelpDesks.forEach((desk, idx) => {
        lines.push(`${idx + 1}. *${desk.name}*`);
        if (desk.address) {
          lines.push(`   Address: ${desk.address}`);
        }
        if (desk.phone) {
          lines.push(`   Phone: ${desk.phone}`);
        }
        lines.push('');
      });
    }

    lines.push('---');
    lines.push('Generated by Sahaay - Financial Navigator for Cancer Patients');
    lines.push('No personal data was stored. Privacy-first approach.');

    return lines.join('%0A');
  };

  const handleShareWhatsApp = () => {
    const message = buildWhatsAppMessage();
    const whatsappURL = `https://wa.me/?text=${message}`;
    window.open(whatsappURL, '_blank');
  };

  const handleReadAll = () => {
    if (isReading) {
      stop();
      setIsReading(false);
      return;
    }
    setIsReading(true);
    speak(buildFullSpeechText(), {
      rate: 0.7,
      onEnd: () => setIsReading(false),
    });
  };

  const handlePrint = () => {
    window.print();
  };

  const getAnswerSummary = (): string[] => {
    const summary: string[] = [];
    for (const q of intakeQuestions) {
      const val = answers[q.key];
      if (val === null || val === '' || val === undefined) continue;
      let display: string;
      if (typeof val === 'boolean') {
        display = val ? 'Yes' : 'No';
      } else if (q.type === 'choice' && q.options) {
        const opt = q.options.find((o) => o.value === val);
        display = opt ? opt.label : String(val);
      } else {
        display = String(val);
      }
      summary.push(`${q.question}: ${display}`);
    }
    return summary;
  };

  return (
    <div className="min-h-screen bg-slate-50">
      {/* Header — hidden on print */}
      <header className="bg-white border-b border-slate-200 sticky top-0 z-10 print:hidden">
        <div className="max-w-4xl mx-auto px-5 py-3 flex items-center justify-between">
          <button
            onClick={onHome}
            className="flex items-center gap-1.5 text-slate-600 hover:text-slate-900 text-sm font-medium transition-colors"
          >
            <Home className="w-4 h-4" />
            Home
          </button>
          <div className="flex items-center gap-2 flex-wrap justify-end">
            <button
              onClick={handleShareWhatsApp}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-sm font-medium bg-green-50 text-green-700 hover:bg-green-100 transition-colors"
            >
              <MessageCircle className="w-4 h-4" />
              Share on WhatsApp
            </button>
            <button
              onClick={handleReadAll}
              disabled={!ttsSupported}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-sm font-medium transition-colors ${
                isReading
                  ? 'bg-red-50 text-red-600'
                  : 'bg-sky-100 text-sky-700 hover:bg-sky-200'
              }`}
            >
              {isReading ? <Pause className="w-4 h-4" /> : <Volume2 className="w-4 h-4" />}
              {isReading ? 'Stop' : 'Read Aloud'}
            </button>
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-sm font-medium bg-slate-900 text-white hover:bg-slate-800 transition-colors"
            >
              <Printer className="w-4 h-4" />
              Print / PDF
            </button>
          </div>
        </div>
      </header>

      <div className="max-w-4xl mx-auto px-5 py-8 print:py-4">
        {/* Report title — visible on print */}
        <div className="mb-6 print:block">
          <div className="flex items-center gap-2 mb-2 print:hidden">
            <CheckCircle2 className="w-6 h-6 text-emerald-600" />
            <h1 className="text-2xl font-bold text-slate-900">Your Eligibility Report</h1>
          </div>
          <div className="hidden print:block">
            <h1 className="text-2xl font-bold">Sahaay — Cancer Patient Financial Eligibility Report</h1>
            <p className="text-sm text-slate-500">Generated on {new Date().toLocaleDateString('en-IN', { dateStyle: 'full' })}</p>
            <hr className="my-4" />
          </div>
          <p className="text-slate-600 print:ml-0 ml-8">
            {eligibleCount > 0
              ? `You qualify for ${eligibleCount} scheme${eligibleCount > 1 ? 's' : ''} and ${ngoCount} NGO${ngoCount > 1 ? 's' : ''} that can help.`
              : `${ngoCount} NGO${ngoCount > 1 ? 's' : ''} that can help you were found.`}
          </p>
        </div>

        {/* Eligible Schemes */}
        {eligibleCount > 0 && (
          <section className="mb-8">
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-lg bg-sky-100 flex items-center justify-center">
                <FileText className="w-5 h-5 text-sky-600" />
              </div>
              <h2 className="text-xl font-bold text-slate-900">
                Schemes You Qualify For ({eligibleCount})
              </h2>
            </div>
            <div className="space-y-4">
              {result.eligibleSchemes.map((match, idx) => (
                <div
                  key={match.scheme.id}
                  className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden"
                >
                  <div className="p-5 sm:p-6">
                    <div className="flex items-start justify-between gap-3 mb-3">
                      <div className="flex-1">
                        <div className="flex items-center gap-2 mb-1">
                          <span className="inline-flex items-center justify-center w-6 h-6 rounded-full bg-sky-600 text-white text-xs font-bold">
                            {idx + 1}
                          </span>
                          <h3 className="text-lg font-bold text-slate-900">{match.scheme.scheme_name}</h3>
                          {match.scheme.verified ? (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-emerald-50 text-emerald-700 text-xs font-medium">
                              <CheckCircle2 className="w-3 h-3" />
                              Verified
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full bg-amber-50 text-amber-700 text-xs font-medium">
                              Verify details
                            </span>
                          )}
                        </div>
                        <p className="text-sm text-slate-500 ml-8">{match.scheme.administering_body} · {match.scheme.region}</p>
                      </div>
                    </div>

                    {/* Coverage */}
                    {match.scheme.coverage_amount && (
                      <div className="ml-8 mb-3 inline-flex items-center gap-2 px-3 py-1.5 rounded-lg bg-emerald-50 text-emerald-800 text-sm font-semibold">
                        Coverage: {match.scheme.coverage_amount}
                      </div>
                    )}

                    {/* Why you qualify */}
                    <div className="ml-8 mb-3">
                      <p className="text-xs font-semibold text-slate-400 uppercase tracking-wide mb-1.5">Why you qualify</p>
                      <ul className="space-y-1">
                        {match.reasons.map((reason, i) => (
                          <li key={i} className="text-sm text-slate-700 flex items-start gap-2">
                            <ArrowRight className="w-3.5 h-3.5 text-sky-500 mt-0.5 flex-shrink-0" />
                            {reason}
                          </li>
                        ))}
                      </ul>
                    </div>

                    {/* Documents needed */}
                    <div className="ml-8 mb-3">
                      <p className="text-xs font-semibold text-slate-400 uppercase tracking-wide mb-1.5">Documents you need</p>
                      <div className="flex flex-wrap gap-2">
                        {match.documentsNeeded.map((doc, i) => (
                          <span key={i} className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-slate-100 text-slate-700 text-xs font-medium">
                            <FileText className="w-3 h-3" />
                            {doc}
                          </span>
                        ))}
                      </div>
                    </div>

                    {/* How to apply */}
                    {match.scheme.how_to_apply && (
                      <div className="ml-8 mb-3">
                        <p className="text-xs font-semibold text-slate-400 uppercase tracking-wide mb-1">How to apply</p>
                        <p className="text-sm text-slate-700">{match.scheme.how_to_apply}</p>
                      </div>
                    )}

                    {/* Official link */}
                    {match.scheme.official_url && (
                      <a
                        href={match.scheme.official_url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="ml-8 inline-flex items-center gap-1.5 text-sm text-sky-600 hover:text-sky-700 font-medium"
                      >
                        <ExternalLink className="w-3.5 h-3.5" />
                        Official website
                      </a>
                    )}
                  </div>
                </div>
              ))}
            </div>
          </section>
        )}

        {/* No schemes found message */}
        {eligibleCount === 0 && (
          <section className="mb-8">
            <div className="bg-amber-50 border border-amber-200 rounded-2xl p-6 text-center">
              <p className="text-amber-800 font-medium mb-2">
                No government schemes matched your answers.
              </p>
              <p className="text-amber-700 text-sm">
                This doesn't mean no help is available. The NGOs below may still be able to assist you.
                You can also try updating your answers if any details were incorrect.
              </p>
            </div>
          </section>
        )}

        {/* NGO Section */}
        {result.eligibleNGOs.length > 0 && (
          <section className="mb-8">
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-lg bg-rose-100 flex items-center justify-center">
                <HandHeart className="w-5 h-5 text-rose-600" />
              </div>
              <h2 className="text-xl font-bold text-slate-900">
                NGOs That Can Help ({result.eligibleNGOs.length})
              </h2>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {result.eligibleNGOs.map((ngo) => (
                <div key={ngo.id} className="bg-white rounded-2xl border border-slate-200 shadow-sm p-5">
                  <h3 className="font-bold text-slate-900 mb-1">{ngo.org_name}</h3>
                  <p className="text-sm text-slate-600 mb-2">{ngo.focus_area}</p>
                  {ngo.scale_reach && (
                    <p className="text-xs text-slate-500 mb-2">{ngo.scale_reach}</p>
                  )}
                  {ngo.contact_info && (
                    <a
                      href={ngo.contact_info.startsWith('http') ? ngo.contact_info : undefined}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="inline-flex items-center gap-1.5 text-sm text-rose-600 hover:text-rose-700 font-medium"
                    >
                      <ExternalLink className="w-3.5 h-3.5" />
                      {ngo.contact_info}
                    </a>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Help Desks */}
        {result.nearbyHelpDesks.length > 0 && (
          <section className="mb-8">
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-lg bg-amber-100 flex items-center justify-center">
                <MapPin className="w-5 h-5 text-amber-600" />
              </div>
              <h2 className="text-xl font-bold text-slate-900">
                Nearest Help Desks ({result.nearbyHelpDesks.length})
              </h2>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {result.nearbyHelpDesks.map((desk) => (
                <div key={desk.id} className="bg-white rounded-2xl border border-slate-200 shadow-sm p-5">
                  <div className="flex items-start gap-2 mb-2">
                    <Building2 className="w-5 h-5 text-amber-600 mt-0.5 flex-shrink-0" />
                    <div>
                      <h3 className="font-bold text-slate-900">{desk.name}</h3>
                      {desk.organization_type && (
                        <span className="text-xs text-slate-500">{desk.organization_type}</span>
                      )}
                    </div>
                  </div>
                  {desk.address && (
                    <p className="text-sm text-slate-600 mb-2 ml-7">{desk.address}</p>
                  )}
                  {desk.phone && (
                    <a
                      href={`tel:${desk.phone}`}
                      className="inline-flex items-center gap-1.5 text-sm text-amber-700 hover:text-amber-800 font-medium ml-7"
                    >
                      <Phone className="w-3.5 h-3.5" />
                      {desk.phone}
                    </a>
                  )}
                </div>
              ))}
            </div>
          </section>
        )}

        {/* Next Steps */}
        {result.nextSteps.length > 0 && (
          <section className="mb-8">
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-lg bg-violet-100 flex items-center justify-center">
                <ListChecks className="w-5 h-5 text-violet-600" />
              </div>
              <h2 className="text-xl font-bold text-slate-900">Your Next Steps</h2>
            </div>
            <div className="bg-white rounded-2xl border border-slate-200 shadow-sm p-5">
              <ol className="space-y-3">
                {result.nextSteps.map((step, i) => (
                  <li key={i} className="flex items-start gap-3">
                    <span className="inline-flex items-center justify-center w-6 h-6 rounded-full bg-violet-600 text-white text-xs font-bold flex-shrink-0 mt-0.5">
                      {i + 1}
                    </span>
                    <span className="text-sm text-slate-700">{step}</span>
                  </li>
                ))}
              </ol>
            </div>
          </section>
        )}

        {/* Answer summary — for print only */}
        <section className="hidden print:block mb-8">
          <h2 className="text-lg font-bold mb-3">Your Answers</h2>
          <ul className="text-sm space-y-1">
            {getAnswerSummary().map((line, i) => (
              <li key={i}>{line}</li>
            ))}
          </ul>
        </section>

        {/* Privacy notice */}
        <section className="mb-8 print:hidden">
          <div className="bg-slate-900 text-white rounded-2xl p-5 text-center">
            <p className="text-sm text-slate-300">
              Your answers were used only to generate this report. No personal data was stored or shared.
            </p>
          </div>
        </section>

        {/* Actions — hidden on print */}
        <div className="flex flex-col sm:flex-row gap-3 print:hidden">
          <button
            onClick={onRestart}
            className="flex-1 flex items-center justify-center gap-2 px-6 py-3.5 bg-white border border-slate-300 text-slate-700 rounded-xl font-semibold hover:bg-slate-50 transition-colors"
          >
            <RefreshCw className="w-5 h-5" />
            Start Over
          </button>
          <button
            onClick={onHome}
            className="flex-1 flex items-center justify-center gap-2 px-6 py-3.5 bg-sky-600 text-white rounded-xl font-semibold hover:bg-sky-700 transition-colors"
          >
            <Home className="w-5 h-5" />
            Back to Home
          </button>
        </div>
      </div>
    </div>
  );
}
